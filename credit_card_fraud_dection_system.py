from sklearn.model_selection import train_test_split

RANDOM_SEED = 42

# Separate feature columns from target label
X = df.drop(columns=["Class"])
y = df["Class"]

# Split: Reserve 20% of data for the final evaluation step
X_train_val, X_test, y_train_val, y_test = train_test_split(
    X, y,
    test_size=0.20,
    stratify=y,
    random_state=RANDOM_SEED
)

# Split: Subdivide remaining 80% into 60% actual training and 20% validation
X_train, X_val, y_train, y_val = train_test_split(
    X_train_val, y_train_val,
    test_size=0.25,
    stratify=y_train_val,
    random_state=RANDOM_SEED
)

print("Training set:", X_train.shape)
print("Validation set:", X_val.shape)
print("Testing set:", X_test.shape)

# Print rates to confirm stratification preserved the exact class ratio across splits
print("\nFraud rates:")
print("Train:", round(y_train.mean() * 100, 4), "%")
print("Validation:", round(y_val.mean() * 100, 4), "%")
print("Test:", round(y_test.mean() * 100, 4), "%")

from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import StandardScaler

from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier
from sklearn.ensemble import RandomForestClassifier

# Helper to dynamically build pipelines ensuring proper scaling and imputation
def build_pipeline(classifier):
    return Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("scaler", StandardScaler()),
        ("classifier", classifier)
    ])

# Initialize classifiers with class_weight="balanced" to address minority class imbalance
models = {
    "Logistic Regression": build_pipeline(
        LogisticRegression(
            class_weight="balanced",
            max_iter=1000,
            solver="lbfgs",
            random_state=RANDOM_SEED
        )
    ),

    "Decision Tree": build_pipeline(
        DecisionTreeClassifier(
            class_weight="balanced",
            max_depth=8,
            min_samples_leaf=20,
            random_state=RANDOM_SEED
        )
    ),

    "Random Forest": build_pipeline(
        RandomForestClassifier(
            n_estimators=200,
            class_weight="balanced",
            max_depth=10,
            n_jobs=-1,
            random_state=RANDOM_SEED
        )
    )
}

print("Models created:")
for name in models:
    print("-", name)

from sklearn.metrics import f1_score
from time import time

# Construct 200 candidate decision thresholds to optimize the F1-score
thresholds = np.linspace(0.01, 0.99, 200)

trained_models = {}
validation_results = {}

for name, model in models.items():
    print(f"\nTraining {name}...")

    # Measure exact training duration
    start_time = time()
    model.fit(X_train, y_train)
    elapsed = time() - start_time

    # Predict class probabilities on the validation set
    val_proba = model.predict_proba(X_val)[:, 1]

    # Evaluate F1 performance across all 200 possible thresholds
    threshold_scores = []
    for threshold in thresholds:
        val_pred = (val_proba >= threshold).astype(int)
        score = f1_score(y_val, val_pred, zero_division=0)
        threshold_scores.append(score)

    # Locate threshold that produced the absolute highest validation F1 score
    best_index = int(np.argmax(threshold_scores))
    best_threshold = float(thresholds[best_index])
    best_val_f1 = float(threshold_scores[best_index])

    trained_models[name] = model
    validation_results[name] = {
        "threshold": best_threshold,
        "validation_f1": best_val_f1,
        "training_seconds": elapsed
    }

    # Print training summary and optimal validation configuration
    print(f"Training time: {elapsed:.2f} seconds")
    print(f"Best validation threshold: {best_threshold:.4f}")
    print(f"Best validation F1: {best_val_f1:.4f}")

print("\nTraining complete.")

best_model_name = max(
    validation_results,
    key=lambda name: validation_results[name]["validation_f1"]
)

best_model = trained_models[best_model_name]
best_threshold = validation_results[best_model_name]["threshold"]

print("Selected model:", best_model_name)
print("Selected threshold:", round(best_threshold, 4))
print(
    "Validation F1:",
    round(validation_results[best_model_name]["validation_f1"], 4)
)

from sklearn.metrics import (
    precision_score,
    recall_score,
    f1_score,
    roc_auc_score,
    average_precision_score,
    confusion_matrix,
    classification_report
)

test_results = {}
test_probabilities = {}
test_predictions = {}

for name, model in trained_models.items():
    threshold = validation_results[name]["threshold"]

    # Final predictions on the held-out test set
    probabilities = model.predict_proba(X_test)[:, 1]
    predictions = (probabilities >= threshold).astype(int)

    test_probabilities[name] = probabilities
    test_predictions[name] = predictions

    test_results[name] = {
        "Threshold": threshold,
        "Precision": precision_score(
            y_test, predictions, zero_division=0
        ),
        "Recall": recall_score(
            y_test, predictions, zero_division=0
        ),
        "F1": f1_score(
            y_test, predictions, zero_division=0
        ),
        "ROC-AUC": roc_auc_score(y_test, probabilities),
        "PR-AUC": average_precision_score(y_test, probabilities)
    }

results_df = pd.DataFrame(test_results).T
results_df.index.name = "Model"

display(results_df.round(4))

print("\nSelected model classification report:")
print(classification_report(
    y_test,
    test_predictions[best_model_name],
    target_names=["Legitimate", "Fraud"],
    zero_division=0
))

best_predictions = test_predictions[best_model_name]

cm = confusion_matrix(
    y_test,
    best_predictions,
    labels=[0, 1]
)

